// Generate the undo for scripts/out/repair-tn-quotes.sql.
//
// The repair writes prod scripture data by direct SQL, so it ships with a way
// back. It reads the sidecar scan-tn-quotes.mjs --repair writes alongside the
// SQL (scripts/out/repair-tn-quotes.json): for every repaired row, the exact
// pre-repair quote and version, and the exact quote the repair wrote. The
// rollback restores the bytes that were there, not a re-derived guess.
//
// Run it BEFORE applying the repair, so the undo exists before it is needed:
//   REPAIR_ACTOR=<users.id> node --experimental-strip-types --no-warnings \
//     scripts/rollback-tn-quotes.mjs [scripts/out/repair-tn-quotes.json]
//   → scripts/out/rollback-tn-quotes.sql
//
// Each UPDATE is guarded on BOTH the post-repair version AND the row still
// holding the repair's quote. The version alone is not proof the repair
// landed: if the repair's own version guard lost a race to a translator who
// moved the row from 5 to 6, the repair no-op'd — and a rollback keyed on
// "version = 6" would then read the translator's edit as ours and overwrite
// it. Requiring quote = <what we wrote> means the rollback touches a row only
// when it demonstrably still carries the repair. A row that has moved on in
// either respect is left alone and shows up as a shortfall in the reported
// changes count.
//
// The rollback is itself an ordinary edit: it bumps `version` FORWARD and
// writes its own edit_log row, exactly as the repair did. It must not rewind
// the version — the repair's audit row already occupies old+1, and rewinding
// to old would let the translator's next save land a second entry at old+1
// (the history route orders by new_version and warns that duplicates break
// it). Re-running the scan afterwards still sees the original quote; only the
// version number is higher.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sidecarPath = process.argv[2] ?? "scripts/out/repair-tn-quotes.json";

const sidecarFile = resolve(repoRoot, sidecarPath);
if (!existsSync(sidecarFile)) {
  console.error(`no repair sidecar at ${sidecarFile} — run scan-tn-quotes.mjs --repair first`);
  process.exit(1);
}
const sidecar = JSON.parse(readFileSync(sidecarFile, "utf8"));
const entries = Array.isArray(sidecar?.rows) ? sidecar.rows : null;
if (!entries) {
  console.error("sidecar is malformed (expected { generatedAt, book, rows: [...] }) — regenerate it");
  process.exit(1);
}
const bad = entries.filter(
  (e) => typeof e.book !== "string" || typeof e.id !== "string" || typeof e.oldQuote !== "string" ||
    typeof e.newQuote !== "string" || !(Number.isInteger(e.oldVersion) && e.oldVersion >= 1),
);
if (bad.length) {
  console.error(`sidecar is malformed (${bad.length} bad entr${bad.length === 1 ? "y" : "ies"}) — regenerate it`);
  process.exit(1);
}
// The SQL this undoes carries the same stamp in its header. If the two were
// generated by different runs the rollback would target the wrong versions
// and silently no-op — so make the operator confirm they match.
const stamp = `${sidecar.generatedAt ?? "?"}${sidecar.book ? ` BOOK=${sidecar.book}` : ""}`;
console.log(`sidecar run: ${stamp} — check this matches the "-- run:" line of the repair SQL you applied`);

const esc = (s) => String(s).replace(/'/g, "''");
const actor = Number(process.env.REPAIR_ACTOR);
if (!(Number.isInteger(actor) && actor > 0)) {
  console.error("refusing to emit SQL: REPAIR_ACTOR must be a users.id (same value the repair used)");
  process.exit(1);
}
const out = [
  "-- Undo for repair-tn-quotes.sql. Restores the quote each row held in the",
  "-- dump taken immediately before the repair, as a NEW version with its own",
  "-- edit_log row (never rewinds a version number).",
  "-- Generated by scripts/rollback-tn-quotes.mjs — do not hand-edit.",
  `-- undoes run: ${stamp}`,
  `-- ${entries.length} row(s). Each UPDATE fires only if the row is still at the post-repair`,
  "-- version AND still holds the repaired quote; compare the reported changes count.",
  "",
];
for (const e of entries) {
  out.push(
    `UPDATE tn_rows SET quote = '${esc(e.oldQuote)}', version = version + 1, updated_at = unixepoch(), updated_by = ${actor}`,
    `  WHERE book = '${esc(e.book)}' AND id = '${esc(e.id)}' AND version = ${e.oldVersion + 1} AND quote = '${esc(e.newQuote)}'`,
    `    AND deleted_at IS NULL AND trashed_at IS NULL;`,
    `INSERT INTO edit_log (kind, row_key, book, user_id, prev_version, new_version, action, payload_json)`,
    `  SELECT 'tn', id, book, ${actor}, version - 1, version, 'update', json_object('quote', quote)`,
    `    FROM tn_rows WHERE book = '${esc(e.book)}' AND id = '${esc(e.id)}' AND changes() > 0;`,
  );
}
const outDir = resolve(repoRoot, "scripts/out");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "rollback-tn-quotes.sql"), out.join("\n"), "utf8");
console.log(`wrote rollback for ${entries.length} row(s)`);
console.log("each UPDATE is guarded on the post-repair version AND the repaired quote — compare");
console.log("the reported `changes` against this count when applying; a shortfall means those");
console.log("rows were edited after the repair and were deliberately left untouched.");
