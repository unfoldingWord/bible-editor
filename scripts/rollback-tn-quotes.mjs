// Generate the undo for scripts/out/repair-tn-quotes.sql.
//
// The repair writes prod scripture data by direct SQL, so it ships with a way
// back. This reads the repair file to learn WHICH rows it targets, then takes
// each row's pre-repair quote and version from the same dump the repair was
// generated from — so the rollback restores exactly the bytes that were there,
// not a re-derived guess.
//
// Run it BEFORE applying the repair (the dump is the "before" picture):
//   node --experimental-strip-types --no-warnings scripts/rollback-tn-quotes.mjs \
//     scripts/out/dump/tn.json
//   → scripts/out/rollback-tn-quotes.sql
//
// The rollback restores `version` to its old value rather than bumping it, so
// re-running the scan afterwards sees the row exactly as it was.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dumpPath = process.argv[2] ?? "scripts/out/dump/tn.json";
const repairPath = process.argv[3] ?? "scripts/out/repair-tn-quotes.sql";

const repairFile = resolve(repoRoot, repairPath);
if (!existsSync(repairFile)) {
  console.error(`no repair file at ${repairFile} — run scan-tn-quotes.mjs --repair first`);
  process.exit(1);
}
const sql = readFileSync(repairFile, "utf8");

// (book, id) appears twice per repaired row — once in the UPDATE and once in
// the edit_log SELECT. De-duplicate, or the rollback carries every row twice.
const targets = new Map();
for (const m of sql.matchAll(/WHERE book = '([^']+)' AND id = '([^']+)'/g)) {
  targets.set(`${m[1]}|${m[2]}`, { book: m[1], id: m[2] });
}

const raw = JSON.parse(readFileSync(resolve(repoRoot, dumpPath), "utf8"));
const rows = Array.isArray(raw) && Array.isArray(raw[0]?.results) ? raw[0].results : (raw.results ?? raw);
const byKey = new Map(rows.map((r) => [`${r.book}|${r.id}`, r]));

const esc = (s) => String(s).replace(/'/g, "''");
const out = [
  "-- Undo for repair-tn-quotes.sql. Restores the quote and version each row",
  "-- held in the dump taken immediately before the repair.",
  "-- Generated by scripts/rollback-tn-quotes.mjs — do not hand-edit.",
  "",
];
let missing = 0;
for (const { book, id } of targets.values()) {
  const r = byKey.get(`${book}|${id}`);
  if (!r) { missing++; out.push(`-- NOT IN DUMP, cannot restore: ${book} ${id}`); continue; }
  // Guarded on the version the repair LEFT the row at. Without it, a rollback
  // run after a translator has edited the row would silently discard their
  // quote and rewind the version — and reusing an already-issued version number
  // lets the next edit produce a duplicate version-history entry. With the
  // guard, a row that has moved on is simply left alone (and reported by the
  // count mismatch below).
  out.push(
    `UPDATE tn_rows SET quote = '${esc(r.quote)}', version = ${Number(r.version)}, updated_at = unixepoch()`,
    `  WHERE book = '${esc(book)}' AND id = '${esc(id)}' AND version = ${Number(r.version) + 1};`,
  );
}
const outDir = resolve(repoRoot, "scripts/out");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "rollback-tn-quotes.sql"), out.join("\n"), "utf8");
console.log(`wrote rollback for ${targets.size - missing} row(s)` + (missing ? `; ${missing} not found in the dump` : ""));
console.log("each UPDATE is guarded on the post-repair version — compare the reported");
console.log("`changes` against this count when applying; a shortfall means those rows");
console.log("were edited after the repair and were deliberately left untouched.");
